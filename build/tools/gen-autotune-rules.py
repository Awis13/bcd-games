"""Generate app/Madeira/AutoTuneRules.generated.swift from build/tools/autotune_rules.py.

madeira-bcd: auto-tune (docs/AUTO-TUNE.md). The rules are embedded as JSON, which
AutoTuneRules.load decodes for one analysis (the same decoder reads the
Documents/autotune-rules.json override).

    build/tools/gen-autotune-rules.py           rewrite the Swift file
    build/tools/gen-autotune-rules.py --check   exit 1 if it is out of date
"""
import importlib.util
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "app", "Madeira", "AutoTuneRules.generated.swift")


def load():
    spec = importlib.util.spec_from_file_location("autotune_rules", os.path.join(ROOT, "build", "tools", "autotune_rules.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render(rules):
    body = json.dumps(rules, indent=1, ensure_ascii=True, sort_keys=True)
    assert '"##' not in body and '##"' not in body, "a rule string contains the raw-string delimiter"
    return ("// SPDX-License-Identifier: GPL-3.0-only\n"
            "// Copyright 2026 thebcd69 (BCD)\n"
            "// BCD Material: additional terms under GPL-3.0 section 7 apply; see LICENSE-BCD.md.\n"
            "// Generated by build/tools/gen-autotune-rules.py from build/tools/autotune_rules.py.\n"
            "// Do not edit by hand: run the script (tests/host/check-autotune.py fails when stale).\n"
            "// madeira-bcd: auto-tune (docs/AUTO-TUNE.md).\n\n"
            "enum AutoTuneBuiltInRules {\n"
            "    static let json = ##\"\"\"\n" + body + "\n\"\"\"##\n}\n")


def main():
    text = render(load().RULES)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("AutoTuneRules.generated.swift is out of date: run build/tools/gen-autotune-rules.py")
            return 1
        print("AutoTuneRules.generated.swift is current")
        return 0
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
