#!/bin/bash
# Compiles tests/dxtests/cube.hlsl, offline, into tests/dxtests/cube_shaders.h: the cube's vertex and pixel
# shaders as Shader Model 4.0 bytecode (Direct3D 10) and 5.0 bytecode (Direct3D 11). The test programs
# (d3d10_cube.c, d3d11_cube.c) include the header, so they need no shader compiler at run time and the
# bytes that reach the device are the same on every build. Run it again after a change to cube.hlsl; the
# header records the SHA-256 of the HLSL it came from, and tests/host/check-dx-tests.py fails when they differ.
#
# The compiler is Wine's bundled vkd3d-shader (wine/libs/vkd3d), built here for the Mac with a small driver
# (tests/dxtests/hlslc.c). That needs the wine submodule's native build tree for the generated parser
# sources and headers (wine/build-native, which a build clone has). Usage, from anywhere:
#   tools/gen-dx-test-shaders.sh [wine tree]        (default: <repository>/wine, else ~/madeira-bcd/wine)
set -eu
R="$(cd "$(dirname "$0")/.." && pwd)"
W="${1:-${WINE_TREE:-$R/wine}}"
[ -d "$W/build-native/libs/vkd3d/libs/vkd3d-shader" ] || W="$HOME/madeira-bcd/wine"
V="$W/libs/vkd3d"
G="$W/build-native/libs/vkd3d/libs/vkd3d-shader"
for f in "$V/libs/vkd3d-shader/hlsl.y" "$G/hlsl.tab.c" "$G/hlsl.yy.c" "$G/preproc.tab.c" "$G/preproc.yy.c" "$W/build-native/include/objidlbase.h"; do
    [ -f "$f" ] || { echo "gen-dx-test-shaders: $f is missing: this needs the wine submodule with its native build (wine/build-native)" >&2; exit 1; }
done
OUT="${OUT:-$R/build/dx-tests}"
SRC="$R/tests/dxtests"
mkdir -p "$OUT/obj"

FLAGS=(-O1 -w -DLIBVKD3D_SHADER_SOURCE -DLIBVKD3D_SOURCE -DWINE_NO_NAMELESS_EXTENSION
       -DHAVE_SYNC_ADD_AND_FETCH=1 -DHAVE_SYNC_BOOL_COMPARE_AND_SWAP=1
       -I"$V/include" -I"$V/include/private" -I"$V/libs/vkd3d-shader" -I"$G" -I"$V" -I"$W/include" -I"$W/build-native/include")
echo "=== vkd3d-shader for this Mac ==="
for f in libs/vkd3d-common/debug.c libs/vkd3d-common/error.c libs/vkd3d-common/memory.c libs/vkd3d-common/utf8.c \
         libs/vkd3d-shader/checksum.c libs/vkd3d-shader/d3d_asm.c libs/vkd3d-shader/d3dbc.c libs/vkd3d-shader/dxbc.c \
         libs/vkd3d-shader/dxil.c libs/vkd3d-shader/fx.c libs/vkd3d-shader/glsl.c libs/vkd3d-shader/hlsl.c \
         libs/vkd3d-shader/hlsl_codegen.c libs/vkd3d-shader/hlsl_constant_ops.c libs/vkd3d-shader/ir.c \
         libs/vkd3d-shader/msl.c libs/vkd3d-shader/spirv.c libs/vkd3d-shader/tpf.c libs/vkd3d-shader/vkd3d_shader_main.c; do
    clang "${FLAGS[@]}" -c "$V/$f" -o "$OUT/obj/$(basename "$f" .c).o"
done
for f in hlsl.tab hlsl.yy preproc.tab preproc.yy; do
    clang "${FLAGS[@]}" -c "$G/$f.c" -o "$OUT/obj/$f.o"
done
clang -O1 -w -I"$V/include" -I"$V/include/private" -c "$SRC/hlslc.c" -o "$OUT/obj/hlslc.o"
clang "$OUT/obj/"*.o -o "$OUT/hlslc"

echo "=== cube.hlsl ==="
HLSL="$SRC/cube.hlsl"
for t in "vs_main vs_4_0" "ps_main ps_4_0" "vs_main vs_5_0" "ps_main ps_5_0"; do
    set -- $t
    "$OUT/hlslc" "$HLSL" "$1" "$2" "$OUT/cube_$2.dxbc"
done

HDR="$SRC/cube_shaders.h"
{
    echo "// SPDX-License-Identifier: GPL-3.0-only"
    echo "// Copyright 2026 thebcd69 (BCD)"
    echo "// BCD Material: additional terms under GPL-3.0 section 7 apply; see LICENSE-BCD.md."
    echo "//"
    echo "// Generated by tools/gen-dx-test-shaders.sh from cube.hlsl with Wine's bundled vkd3d-shader. Do not edit."
    echo "// source-sha256: $(shasum -a 256 "$HLSL" | cut -d' ' -f1)"
    for p in vs_4_0 ps_4_0 vs_5_0 ps_5_0; do
        echo
        echo "static const unsigned char cube_$p[] = {"
        xxd -i < "$OUT/cube_$p.dxbc"
        echo "};"
    done
} > "$HDR"
echo "wrote $HDR"
